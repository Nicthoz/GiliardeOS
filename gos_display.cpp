static void oledCmds(const uint8_t* c, uint8_t n) {
  Wire.beginTransmission(OLED_ADDR);
  Wire.write((uint8_t)0x00);
  for (uint8_t i = 0; i < n; i++) Wire.write(c[i]);
  Wire.endTransmission();
}

void gfx_begin() {
  Wire.begin();
  Wire.setClock(400000);
  for (uint8_t i = 0; i < sizeof(INIT_SEQ); i++) {
    uint8_t c = pgm_read_byte(&INIT_SEQ[i]);
    oledCmds(&c, 1);
  }
  gfx_clear();
  gfx_show();
}

void gfx_clear() { memset(fb, 0, sizeof(fb)); }

void gfx_show() {
  static const uint8_t win[] = { 0x21, 0, 127, 0x22, 0, 7 };
  oledCmds(win, sizeof(win));
  for (uint16_t i = 0; i < sizeof(fb); i += 16) {
    Wire.beginTransmission(OLED_ADDR);
    Wire.write((uint8_t)0x40);
    Wire.write(fb + i, 16);
    Wire.endTransmission();
  }
}

void gfx_invert_view(uint8_t pages) {
  uint16_t n = (uint16_t)pages * SCR_W;
  for (uint16_t i = 0; i < n; i++) fb[i] ^= 0xFF;
}

void gfx_pixel(int16_t x, int16_t y, uint8_t c) {
  if ((uint16_t)x >= SCR_W || (uint16_t)y >= SCR_H) return;
  uint16_t i = x + (y >> 3) * SCR_W;
  uint8_t m = 1 << (y & 7);
  if (c == 1) fb[i] |= m;
  else if (c == 0) fb[i] &= ~m;
  else fb[i] ^= m;
}

void gfx_hline(int16_t x, int16_t y, int16_t w, uint8_t c) {
  for (int16_t i = 0; i < w; i++) gfx_pixel(x + i, y, c);
}
void gfx_vline(int16_t x, int16_t y, int16_t h, uint8_t c) {
  for (int16_t i = 0; i < h; i++) gfx_pixel(x, y + i, c);
}
void gfx_rect(int16_t x, int16_t y, int16_t w, int16_t h, uint8_t c) {
  gfx_hline(x, y, w, c); gfx_hline(x, y + h - 1, w, c);
  gfx_vline(x, y, h, c); gfx_vline(x + w - 1, y, h, c);
}
void gfx_fill(int16_t x, int16_t y, int16_t w, int16_t h, uint8_t c) {
  for (int16_t j = 0; j < h; j++) gfx_hline(x, y + j, w, c);
}
void gfx_circle_fill(int16_t cx, int16_t cy, int8_t r, uint8_t c) {
  for (int8_t y = -r; y <= r; y++)
    for (int8_t x = -r; x <= r; x++)
      if ((int16_t)x * x + (int16_t)y * y <= (int16_t)r * r + r) gfx_pixel(cx + x, cy + y, c);
}

static void drawChar(int16_t x, int16_t y, char ch, uint8_t s, uint8_t c) {
  if (ch >= 'a' && ch <= 'z') ch -= 32;
  if (ch < 32 || ch > 90) ch = '?';
  const uint8_t* g = FONT + (uint8_t)(ch - 32) * 5;
  for (uint8_t col = 0; col < 5; col++) {
    uint8_t bits = pgm_read_byte(g + col);
    for (uint8_t row = 0; row < 7; row++) {
      if (bits & (1 << row)) {
        if (s == 1) gfx_pixel(x + col, y + row, c);
        else gfx_fill(x + col * s, y + row * s, s, s, c);
      }
    }
  }
}

void gfx_text(int16_t x, int16_t y, const char* s, uint8_t scale, uint8_t c) {
  while (*s) { drawChar(x, y, *s++, scale, c); x += 6 * scale; }
}
void gfx_textP(int16_t x, int16_t y, const char* s, uint8_t scale, uint8_t c) {
  char ch;
  while ((ch = pgm_read_byte(s++))) { drawChar(x, y, ch, scale, c); x += 6 * scale; }
}
void gfx_num(int16_t x, int16_t y, int32_t n, uint8_t scale, uint8_t c) {
  char b[12];
  ltoa(n, b, 10);
  gfx_text(x, y, b, scale, c);
}
